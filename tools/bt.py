#!/usr/bin/env python3
"""Backtest driver for FiboAdaptiveEA inside the `mt5` Docker container.

Usage
-----
  python3 tools/bt.py run jobs.json      # run every job, sequentially, one terminal
  python3 tools/bt.py report [logfile]   # parse the newest tester log into a table

Job JSON schema
---------------
[
  {"label": "v71_A_jul",
   "expert": "FiboAdaptiveEA_v7.1",
   "from": "2026.07.01",
   "to":   "2026.08.01",
   "deposit": 100,
   "model": 4,
   "inputs": {"InpFadeMode": "true", "InpTP_R": "2.5"}}
]

`to` is EXCLUSIVE (MT5 tester semantics): a full month = first day of next month.
Dates are in the format MT5 expects: YYYY.MM.DD

Sweep spec schema (compact alternative to the job list)
------------------------------------------------------
{
  "expert": "FiboAdaptiveEA_v7.0",
  "prefix": "v70payoff",
  "deposit": 100,
  "months": [["Jul", "2026.07.01", "2026.08.01"],
             ["Aug", "2026.08.01", "2026.09.01"]],
  "months_filter": ["Jul", "Aug"],          # optional
  "base":     {"InpUsePartial": "false"},    # shared inputs
  "variants": [{"InpTP_R": "2.5", "tag": "tp25"},   # "tag" builds the label
               {"InpTP_R": "3.0", "tag": "tp30"}]
}
"""

import json
import os
import re
import subprocess
import sys
import time

DOCKER = "/Applications/Docker.app/Contents/Resources/bin/docker"
MTR = "/config/.wine/drive_c/Program Files/MetaTrader 5"
HOST_TMP = "/tmp/fibo_bt"
# MT5 only accepts a /config: path it can resolve inside the Wine prefix.
# The proven form is a RELATIVE path from the terminal install directory,
# so the .ini files are copied into the MT5 root and referenced by name.
CONTAINER_INI_DIR = MTR
CONTAINER_TMP = "/tmp/fibo_bt"

INI_TEMPLATE = """; generated by tools/bt.py
[Tester]
Expert={expert}
Symbol=XAUUSDm
Period=M5
Optimization=0
Model={model}
FromDate={frm}
ToDate={to}
ForwardMode=0
Deposit={deposit}
Currency=USD
Leverage=2000
ExecutionMode=0
Visual=0
Report={label}
ReplaceReport=1
ShutdownTerminal=1
"""


def sh(args, **kw):
    return subprocess.run(args, capture_output=True, text=True, **kw)


def docker(args):
    return sh([DOCKER] + args)


def build_job_files(jobs):
    os.makedirs(HOST_TMP, exist_ok=True)
    for j in jobs:
        ini = INI_TEMPLATE.format(
            expert=j["expert"],
            model=j.get("model", 4),
            frm=j["from"],
            to=j["to"],
            deposit=j.get("deposit", 100),
            label=j["label"],
        )
        inputs = j.get("inputs") or {}
        if inputs:
            ini += "\n[TesterInputs]\n"
            for k in sorted(inputs):
                ini += "%s=%s\n" % (k, inputs[k])
        path = os.path.join(HOST_TMP, j["label"] + ".ini")
        with open(path, "w") as fh:
            fh.write(ini)
        j["_host_ini"] = path


def push_jobs(jobs):
    docker(["exec", "mt5", "mkdir", "-p", CONTAINER_TMP])
    for j in jobs:
        j["_ini_name"] = "bt_%s.ini" % j["label"]
        r = docker(["cp", j["_host_ini"], "mt5:%s/%s" % (CONTAINER_INI_DIR, j["_ini_name"])])
        if r.returncode != 0:
            raise SystemExit("docker cp failed: " + r.stderr)


def run_jobs(jobs, wait=True):
    build_job_files(jobs)
    push_jobs(jobs)
    lines = ["#!/bin/bash", "cd \"%s\" || exit 1" % MTR,
             "pkill -f 'terminal6[4]\\.exe' 2>/dev/null; sleep 2",
             "LOG=\"Tester/logs/$(date -u +%Y%m%d).log\"",
             "mtime() { stat -c %Y \"$LOG\" 2>/dev/null || date -r \"$LOG\" +%s 2>/dev/null || echo 0; }",
             "run_one() {",
             "  ini=$1; label=$2",
             "  before=$(mtime)",
             "  wine terminal64.exe /config:$ini >/dev/null 2>&1 &",
             "  wp=$!; elapsed=0; stall=0",
             "  while kill -0 $wp 2>/dev/null; do",
             "    sleep 10; elapsed=$((elapsed+10))",
             "    now=$(mtime)",
             "    if [ \"$now\" != \"$before\" ]; then before=$now; stall=0; else stall=$((stall+10)); fi",
             "    if [ $elapsed -gt 900 ] || [ $stall -gt 240 ]; then",
             "      echo \"WATCHDOG kill $label elapsed=$elapsed stall=$stall\"",
             "      pkill -f 'terminal6[4]\\.exe' 2>/dev/null; sleep 3; break",
             "    fi",
             "  done",
             "  wait $wp 2>/dev/null",
             "  sleep 2",
             "}",
             "echo RUNNER_START $(date +%H:%M:%S)"]
    for j in jobs:
        lines.append("echo JOB_START %s $(date +%%H:%%M:%%S)" % j["label"])
        lines.append("run_one \"%s\" \"%s\"" % (j["_ini_name"], j["label"]))
        lines.append("echo JOB_END %s $(date +%%H:%%M:%%S)" % j["label"])
    lines.append("echo RUNNER_DONE $(date +%H:%M:%S)")
    script = "\n".join(lines) + "\n"
    os.makedirs(HOST_TMP, exist_ok=True)
    with open(os.path.join(HOST_TMP, "run_batch.sh"), "w") as fh:
        fh.write(script)
    docker(["cp", os.path.join(HOST_TMP, "run_batch.sh"),
            "mt5:%s/run_batch.sh" % CONTAINER_TMP])
    if not wait:
        return docker(["exec", "-d", "mt5", "bash", CONTAINER_TMP + "/run_batch.sh"])
    return docker(["exec", "mt5", "bash", CONTAINER_TMP + "/run_batch.sh"])


RUN_RE = re.compile(
    r"testing of Experts\\(FiboAdaptiveEA_v[\d.]+)\.ex5 from (\S+ \S+) to (\S+ \S+) started with inputs")
PARAM_RE = re.compile(r"^..\t0\t\S+\tCore 01\t\s+([A-Za-z_0-9]+)=(.*)$")
FINAL_RE = re.compile(r"final balance (-?[\d.]+) USD")
NOTENOUGH_RE = re.compile(r"not enough money")


def parse_log(path):
    runs = []
    cur = None
    for i, line in enumerate(open(path, encoding="utf-8", errors="replace")):
        m = RUN_RE.search(line)
        if m:
            if cur:
                cur["endline"] = i
                runs.append(cur)
            cur = {"expert": m.group(1), "from": m.group(2)[:10],
                   "to": m.group(3)[:10], "params": {}, "final": None,
                   "notenough": 0, "line": i, "endline": None}
            continue
        if cur is None:
            continue
        pm = PARAM_RE.match(line)
        if pm:
            cur["params"][pm.group(1)] = pm.group(2).strip()
        fm = FINAL_RE.search(line)
        if fm and cur["final"] is None:
            cur["final"] = float(fm.group(1))
        if NOTENOUGH_RE.search(line):
            cur["notenough"] += 1
    if cur:
        if cur.get("endline") is None:
            cur["endline"] = i + 1
        runs.append(cur)
    return runs


def newest_log():
    r = docker(["exec", "mt5", "bash", "-c",
                "ls -t '%s/Tester/logs/'*.log 2>/dev/null | head -1" % MTR])
    p = r.stdout.strip()
    if not p:
        return None
    local = "/tmp/fibo_last.log"
    docker(["exec", "mt5", "bash", "-c",
            "iconv -f UTF-16 -t UTF-8 '%s' > /tmp/fibo_last.log 2>/dev/null" % p])
    r = docker(["cp", "mt5:/tmp/fibo_last.log", local])
    if r.returncode != 0:
        raise SystemExit("copy log failed: " + r.stderr)
    return local


def expand_spec(spec):
    """Turn a compact sweep spec into a flat job list."""
    if isinstance(spec, list):
        return spec
    jobs = []
    if spec.get("daily"):
        # "daily": [["2026.09", 30], ...] -> one $100-reset run per weekday
        import datetime as _dt
        base = dict(spec.get("base") or {})
        for v in spec["variants"]:
            v = dict(v)
            tag = v.pop("tag", None) or "run"
            expert = v.pop("expert", None) or spec["expert"]
            inputs = dict(base)
            inputs.update(v)
            for ym, lastday in spec["daily"]:
                y, m = (int(x) for x in ym.split("."))
                for d in range(1, lastday + 1):
                    day = _dt.date(y, m, d)
                    if day.weekday() >= 5:
                        continue
                    nxt = day + _dt.timedelta(days=1)
                    jobs.append({
                        "label": "%s_%s_%s" % (spec.get("prefix", "d"), tag,
                                               day.strftime("%m%d")),
                        "expert": expert,
                        "from": day.strftime("%Y.%m.%d"),
                        "to": nxt.strftime("%Y.%m.%d"),
                        "deposit": spec.get("deposit", 100),
                        "model": spec.get("model", 4),
                        "inputs": inputs,
                    })
        return jobs
    months = spec["months"]
    if spec.get("months_filter"):
        keep = set(spec["months_filter"])
        months = [m for m in months if m[0] in keep]
    for v in spec["variants"]:
        v = dict(v)
        tag = v.pop("tag", None) or "_".join(
            "%s%s" % (k.replace("Inp", ""), str(val).replace(".", "p"))
            for k, val in sorted(v.items()))
        expert = v.pop("expert", None) or spec["expert"]
        dep = v.pop("deposit", None) or spec.get("deposit", 100)
        inputs = dict(spec.get("base") or {})
        inputs.update(v)
        for mname, frm, to in months:
            jobs.append({
                "label": "%s_%s_%s" % (spec.get("prefix", "r"), tag, mname),
                "expert": expert,
                "from": frm,
                "to": to,
                "deposit": dep,
                "model": spec.get("model", 4),
                "inputs": inputs,
            })
    return jobs


KEYS = ["InpFadeMode", "InpTP_R", "InpSL_ATR", "InpUsePartial", "InpUseBreakEven",
        "InpUseTrailing", "InpDailyStopPct", "InpUseDeepProfile", "InpMaxPositions"]


def cmd_report(argv):
    path = argv[0] if argv else newest_log()
    if not path:
        raise SystemExit("no log")
    runs = parse_log(path)
    print("%-6s %-22s %-11s %-11s %8s  %s" %
          ("#", "expert", "from", "to", "final", " | ".join(KEYS)))
    for i, r in enumerate(runs):
        if r["final"] is None:
            continue
        print("%-6d %-22s %-11s %-11s %8.2f  %s" %
              (i, r["expert"], r["from"], r["to"], r["final"],
               " | ".join("%s=%s" % (k, r["params"].get(k, "-")) for k in KEYS)))


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    cmd = sys.argv[1]
    if cmd == "run":
        jobs = expand_spec(json.load(open(sys.argv[2])))
        print("%d jobs: %s" % (len(jobs), " ".join(j["label"] for j in jobs)))
        t0 = time.time()
        r = run_jobs(jobs)
        print(r.stdout[-4000:])
        if r.returncode != 0:
            print(r.stderr[-2000:])
        print("elapsed %.0fs" % (time.time() - t0))
    elif cmd == "report":
        cmd_report(sys.argv[2:])
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
