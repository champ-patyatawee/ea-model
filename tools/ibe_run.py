#!/usr/bin/env python3
"""Run ImpulseBasketEA tester jobs one at a time, robustly.

The stock batch runner (bt.py) relies on the wine process exiting by itself
and on a single long-lived bash script inside the container. On this machine
the terminal sometimes finishes the test and then never exits, which wedges
the whole batch. This runner instead:

  * starts exactly ONE terminal per job (the brief: never two at a time),
  * wraps it in `timeout`,
  * kills any surviving terminal64 before and after every job,
  * copies the EA's CSV out of the agent sandbox IMMEDIATELY (the tester
    wipes that sandbox when the next job starts),
  * reads the final balance back out of the tester log.

Usage
  python3 tools/ibe_run.py <spec.json> <outdir>
"""
import json
import os
import re
import subprocess
import sys
import time

DOCKER = "/Applications/Docker.app/Contents/Resources/bin/docker"
MTR = "/config/.wine/drive_c/Program Files/MetaTrader 5"
# The tester picks its agent port per run (3002, 3003, ...), so never hard-code
# one: every helper below globs Tester/Agent-*/MQL5/Files.
# Never let the shell split this path on the space in "Program Files": the
# base directory stays quoted and the agent part is matched by -path, not by
# an unquoted glob.
AGENT_ROOT = MTR + "/Tester"
AGENT_FIND = ("find \"%s\" -maxdepth 4 -path '*/MQL5/Files/*.csv' -printf '%%p\\n' 2>/dev/null"
              % AGENT_ROOT)
LOG = MTR + "/Tester/logs"

INI = """; generated by tools/ibe_run.py
[Tester]
Expert={expert}
Symbol=XAUUSDm
Period=M5
Optimization=0
Model={model}
FromDate={frm}
ToDate={to}
ForwardMode=0
Deposit={deposit}
Currency=USD
Leverage=2000
ExecutionMode=0
Visual=0
ReplaceReport=1
ShutdownTerminal=1
{spread}
"""


def sh(args, timeout=600):
    return subprocess.run(args, capture_output=True, text=True, timeout=timeout)


def dx(args, timeout=600):
    return sh([DOCKER, "exec", "mt5"] + args, timeout)


def kill_terminals():
    dx(["bash", "-c", "pkill -f 'terminal6[4]' 2>/dev/null; sleep 2; true"], timeout=60)


def run_job(job, outdir, timeout=300):
    label = job["label"]
    ini = INI.format(expert=job["expert"], model=job.get("model", 2),
                     frm=job["from"], to=job["to"], deposit=job.get("deposit", 100000),
                     spread=("Spread=%s" % job["spread"]) if job.get("spread") else "")
    inputs = job.get("inputs") or {}
    if inputs:
        ini += "\n[TesterInputs]\n"
        for k in sorted(inputs):
            ini += "%s=%s\n" % (k, inputs[k])
    host_ini = "/tmp/ibe_%s.ini" % label
    open(host_ini, "w").write(ini)
    r = sh([DOCKER, "cp", host_ini, "mt5:%s/ibe_%s.ini" % (MTR, label)])
    if r.returncode != 0:
        return "copy failed: " + r.stderr

    kill_terminals()
    # purge CSVs from every agent sandbox AND from the terminal's own MQL5/Files
    # (the tester re-syncs that folder into the sandbox at the start of a test,
    # so a stale file there would be copied out again for every later job)
    dx(["bash", "-c",
        "find \"%s\" -maxdepth 4 -path '*/MQL5/Files/*.csv' -delete 2>/dev/null; "
        "find '%s/MQL5/Files' -maxdepth 1 -name '*.csv' -delete 2>/dev/null; true"
        % (AGENT_ROOT, MTR)], timeout=60)

    cmd = ("cd '%s' && timeout %d wine terminal64.exe /config:ibe_%s.ini >/dev/null 2>&1; "
           "echo WINE_EXIT=$?" % (MTR, timeout, label))
    t0 = time.time()
    dx(["bash", "-c", cmd], timeout=timeout + 60)
    dt = time.time() - t0

    # rescue whatever the EA wrote, then make sure no terminal survives
    os.makedirs(outdir, exist_ok=True)
    # basenames only: the Wine path contains spaces, so never split a full path
    listing = [x for x in dx(["bash", "-c",
                             AGENT_FIND]).stdout.split("\n") if x.strip()]
    copied = []
    for full in listing:
        name = os.path.basename(full)
        r = sh([DOCKER, "cp", "mt5:%s" % full, os.path.join(outdir, name)])
        if r.returncode == 0:
            copied.append(name)
    kill_terminals()

    # final balance from the tester log (the log starts fresh per terminal, so
    # the newest block is the newest job)
    logtxt = dx(["bash", "-c",
                 "iconv -f UTF-16LE -t UTF-8 \"$(ls -t %s/*.log | head -1)\" 2>/dev/null | "
                 "grep -a -E 'final balance|IBE SUMMARY' | tail -4" % LOG]).stdout
    fb = re.findall(r"final balance (-?[\d.]+) USD", logtxt)
    summ = re.findall(r"IBE SUMMARY.*", logtxt)
    return "%.0fs  files=%s  final=%s  %s" % (
        dt, copied, fb[-1] if fb else "?", summ[-1] if summ else "")


def main():
    jobs = json.load(open(sys.argv[1]))
    outdir = sys.argv[2]
    if os.path.exists(os.path.join(outdir, "_done.txt")):
        done = set(open(os.path.join(outdir, "_done.txt")).read().split())
    else:
        done = set()
    t0 = time.time()
    for i, job in enumerate(jobs):
        if job["label"] in done:
            print("[%d/%d] %-16s SKIP (done)" % (i + 1, len(jobs), job["label"]), flush=True)
            continue
        res = run_job(job, outdir)
        print("[%d/%d] %-16s %s  (t+%.0fs)" % (i + 1, len(jobs), job["label"], res, time.time() - t0),
              flush=True)
        with open(os.path.join(outdir, "_done.txt"), "a") as fh:
            fh.write(job["label"] + "\n")
    print("ALL DONE in %.0fs" % (time.time() - t0))


if __name__ == "__main__":
    main()
